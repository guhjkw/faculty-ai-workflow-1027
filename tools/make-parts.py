"""Builds src/ooxml-parts.js: the fixed parts of a 16:9 PowerPoint file (theme, slide master, two layouts,
notes master), taken from python-pptx's default template (MIT) and rescaled from 4:3 to 16:9.
Run once with python-pptx installed:  python3 tools/make-parts.py
The slides, notes, presentation.xml and package files are written by src/ooxml.js at export time."""
import io, json, pathlib, re, zipfile
from pptx import Presentation

ROOT = pathlib.Path(__file__).resolve().parent.parent
buf = io.BytesIO()
_prs = Presentation()
_prs.slides.add_slide(_prs.slide_layouts[1]).notes_slide.notes_text_frame.text = 'x'  # creates the notes master
_prs.save(buf)
z = zipfile.ZipFile(buf)
read = lambda name: z.read(name).decode('utf-8')

def widen(xml):
    """4:3 to 16:9: every x offset and width grows by 4/3 (heights and y are unchanged)."""
    xml = re.sub(r'<a:off x="(\d+)"', lambda m: '<a:off x="%d"' % (int(m.group(1)) * 4 // 3), xml)
    return re.sub(r'<a:ext cx="(\d+)"', lambda m: '<a:ext cx="%d"' % (int(m.group(1)) * 4 // 3), xml)

master = widen(read('ppt/slideMasters/slideMaster1.xml'))
master = re.sub(r'<p:sldLayoutIdLst>.*?</p:sldLayoutIdLst>',
                '<p:sldLayoutIdLst><p:sldLayoutId id="2147483649" r:id="rId1"/><p:sldLayoutId id="2147483650" r:id="rId2"/></p:sldLayoutIdLst>', master)
notes_master = read('ppt/notesMasters/notesMaster1.xml').replace(
    '<a:off x="1143000" y="685800"/><a:ext cx="4572000" cy="3429000"/>',
    '<a:off x="685800" y="1143000"/><a:ext cx="5486400" cy="3086100"/>')
assert '5486400" cy="3086100"' in notes_master
theme = read('ppt/theme/theme1.xml').replace('<a:dk2><a:srgbClr val="1F497D"/>', '<a:dk2><a:srgbClr val="1B2A41"/>') \
    .replace('<a:accent1><a:srgbClr val="4F81BD"/>', '<a:accent1><a:srgbClr val="1F5F8B"/>')
parts = {
    'theme1': theme,
    'theme2': read('ppt/theme/theme2.xml'),
    'master': master,
    'layoutTitle': widen(read('ppt/slideLayouts/slideLayout1.xml')),
    'layoutContent': widen(read('ppt/slideLayouts/slideLayout2.xml')),
    'notesMaster': notes_master,
    'presProps': read('ppt/presProps.xml'),
    'viewProps': read('ppt/viewProps.xml'),
    'tableStyles': read('ppt/tableStyles.xml'),
    'defaultTextStyle': re.search(r'<p:defaultTextStyle>.*</p:defaultTextStyle>', read('ppt/presentation.xml'), re.S).group(0),
}
for k, v in parts.items():
    parts[k] = re.sub(r'>\s+<', '><', v.replace('\r', '').replace('\n', ''))
out = ('// Generated by tools/make-parts.py from python-pptx\'s default template (MIT licence), rescaled to 16:9.\n'
       '// Fixed parts only; do not edit by hand.\n'
       '(function (root, factory) {\n'
       "  if (typeof module === 'object' && module.exports) module.exports = factory();\n"
       '  else root.OoxmlParts = factory();\n'
       "})(typeof self !== 'undefined' ? self : this, function () {\n"
       '  return ' + json.dumps(parts, indent=1, ensure_ascii=True) + ';\n});\n')
(ROOT / 'src' / 'ooxml-parts.js').write_text(out)
print('src/ooxml-parts.js', len(out), 'bytes;', {k: len(v) for k, v in parts.items()})
